// --- Doc comments ------------------------------------------------------------

/** A doc comment, read into the parts the reference shows. */
export type Doc = {
  /** The description, as Markdown. */
  text: string;
  params: { name: string; text: string }[];
  returns: string;
  throws: string[];
  examples: string[];
  /** `undefined` when not tagged; the tag's text (maybe empty) when tagged. */
  experimental: string | undefined;
  deprecated: string | undefined;
  defaultValue: string;
};

/** `{@link A}` and `{@link A | text}` as code or text. */
const links = (s: string): string =>
  s.replace(
    /\{@link(?:code|plain)?\s+([^}|\s]+)\s*(?:\|\s*([^}]*))?\}/g,
    (_m, target: string, text?: string) => (text?.trim() ? text.trim() : `\`${target}\``),
  );

/** A tag's lines as Markdown: continuation lines lose their indent, except inside code fences. */
function tagText(lines: readonly string[]): string {
  let inFence = false;
  const out = lines.map((l) => {
    const opens = /^\s*```/.test(l);
    const kept =
      inFence || opens
        ? l
        : l.replace(/^\s+(?=\S)/, (ws) => (ws.length >= 4 && /^\s*[-*\d]/.test(l) ? ws : ''));
    if (opens) inFence = !inFence;
    return kept;
  });
  return links(out.join('\n').trim());
}

/** Reads a `/** … *\/` comment: its description and the tags the reference shows. */
export function parseDoc(raw: string): Doc {
  const doc: Doc = {
    text: '',
    params: [],
    returns: '',
    throws: [],
    examples: [],
    experimental: undefined,
    deprecated: undefined,
    defaultValue: '',
  };
  if (!raw) return doc;
  const body = raw
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split('\n')
    .map((l) => l.replace(/^\s*\* ?/, '').replace(/^\s+$/, ''));
  // Split into the description and block tags; a tag starts a line, outside code fences.
  const blocks: { tag: string; lines: string[] }[] = [{ tag: '', lines: [] }];
  let fence = false;
  for (const line of body) {
    const t = /^\s*@(\w+)\s?(.*)$/.exec(line);
    if (!fence && t) blocks.push({ tag: t[1] ?? '', lines: [t[2] ?? ''] });
    else blocks.at(-1)?.lines.push(line);
    if (/^\s*```/.test(line)) fence = !fence;
  }
  for (const { tag, lines } of blocks) {
    const text = tagText(lines);
    switch (tag) {
      case '':
        doc.text = text;
        break;
      case 'param': {
        const m = /^(\S+)\s*(?:-\s*)?([\s\S]*)$/.exec(text);
        if (m) doc.params.push({ name: m[1] ?? '', text: m[2] ?? '' });
        break;
      }
      case 'returns':
      case 'return':
        doc.returns = text;
        break;
      case 'throws':
        doc.throws.push(text);
        break;
      case 'example':
        doc.examples.push(text);
        break;
      case 'experimental':
        doc.experimental = text;
        break;
      case 'deprecated':
        doc.deprecated = text;
        break;
      case 'default':
      case 'defaultValue':
        doc.defaultValue = text;
        break;
      case 'remarks':
        doc.text = [doc.text, text].filter(Boolean).join('\n\n');
        break;
      default:
        // @see, @internal and the rest: the reference doesn't show them (decision 29: guide links come from the map).
        break;
    }
  }
  // A modifier tag written inline (`/** The events, by name. @experimental *\/`).
  doc.text = doc.text.replace(/\s@(experimental|deprecated)\b\s*$/, (_m, tag: string) => {
    if (tag === 'experimental') doc.experimental ??= '';
    else doc.deprecated ??= '';
    return '';
  });
  return doc;
}

// --- Rendering ---------------------------------------------------------------

const GROUPS: readonly ExportKind[][] = [
  ['function'],
  ['class'],
  ['const', 'enum', 'namespace'],
  ['interface', 'type'],
];
const groupOf = (k: ExportKind): number => GROUPS.findIndex((g) => g.includes(k));

/** The order on a page: functions, classes, constants, types; alphabetical in each. */
export function ordered(exports: readonly ApiExport[]): ApiExport[] {
  const out = [...exports];
  out.sort(
    (a, b) =>
      groupOf(a.kind) - groupOf(b.kind) ||
      a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }) ||
      a.name.localeCompare(b.name),
  );
  return out;
}

/** GitHub's anchor, which the site uses too: lower case, punctuation dropped, spaces to hyphens. */
export const anchor = (text: string): string =>
  text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s/g, '-');

/** A declaration as a signature: no doc comments, no `declare`, no blank lines. */
export function signature(decl: ApiDecl): string {
  let text = decl.text;
  for (const m of decl.members) if (isInternal(m.doc)) text = text.replace(m.text, '');
  const lines = text
    .replace(/\/\*\*[\s\S]*?\*\//g, '')
    .replace(/^(export )?(declare )?/, '')
    .split('\n')
    .filter((l) => l.trim() !== '');
  const indent = Math.min(
    ...lines.slice(1).map((l) => /^\s*/.exec(l)?.[0].length ?? 0),
    Number.POSITIVE_INFINITY,
  );
  const cut = Number.isFinite(indent) && indent > 2 ? indent - 2 : 0;
  return lines.map((l, i) => (i === 0 ? l : l.slice(cut))).join('\n');
}

/** Whether a doc comment marks its declaration `@internal`: left out of the reference. */
const isInternal = (doc: string): boolean => /(^|\s|\*)@internal\b/.test(doc);

/** Text for one table cell: one line, pipes escaped, code blocks left out. */
const cell = (s: string): string =>
  s
    .replace(/```[\s\S]*?```/g, '')
    .replace(/\s+/g, ' ')
    .replace(/\|/g, '\\|')
    .trim();

/** An example as a fence: as written when it has one, else in a `ts` fence. */
const example = (text: string): string => (/^```/m.test(text) ? text : `\`\`\`ts\n${text}\n\`\`\``);

const experimentalLine = (text: string): string =>
  `**Experimental.**${text ? ` ${text.replace(/\s+/g, ' ')}` : ''}`;

function memberRows(decls: readonly ApiDecl[]): string[] {
  const rows: string[] = [];
  const seen = new Set<string>();
  for (const d of decls) {
    for (const m of d.members) {
      if (
        seen.has(m.name) ||
        m.name.startsWith('#') ||
        /^(private|protected)\s/.test(m.text) ||
        isInternal(m.doc)
      )
        continue;
      seen.add(m.name);
      const after = m.text.slice(m.text.indexOf(m.name) + m.name.length).trimStart();
      const label = `\`${m.name}${/^[(<]/.test(after) ? '()' : after.startsWith('?') ? '?' : ''}\``;
      const doc = parseDoc(m.doc);
      const parts = [
        doc.experimental === undefined ? '' : `**Experimental.**`,
        doc.deprecated === undefined ? '' : '**Deprecated.**',
        doc.text,
        doc.defaultValue ? `Default: ${doc.defaultValue}.` : '',
      ];
      const text = cell(parts.filter(Boolean).join(' '));
      // An undocumented member shows in the declaration above, not as an empty row.
      if (text) rows.push(`| ${label} | ${text} |`);
    }
  }
  return rows;
}

/** Where a page and a guide are, for links. */
type Context = {
  /** The page each entry point is documented on (`host.md`). */
  pageOf: (entry: string) => string;
  /** The page being written. */
  page: string;
  /** The guides that list an export, as Markdown links. */
  guides: (entry: string, name: string) => string[];
};

/** One export's section. */
export function renderExport(e: ApiExport, entry: string, ctx: Context): string {
  const out: string[] = [`### \`${e.name}\``];
  if (e.home !== entry) {
    const page = ctx.pageOf(e.home);
    const href = `${page === ctx.page ? '' : page}#${anchor(e.name)}`;
    // A type that a package nobody reads declares (`@isoloop/protocol`) isn't
    // "re-exported from" the page that documents it: that page doesn't declare it.
    const lead = e.owned ? 'Re-exported from' : 'Also exported by';
    const tail = e.owned ? '' : ', which documents it';
    out.push(`${lead} \`${e.home}\`${tail}: see [\`${e.name}\`](${href}).`);
    return out.join('\n\n');
  }
  const decl = e.decls[0];
  const doc = parseDoc(decl?.doc ?? '');
  const tag = e.tags.find((t) => t.name === 'experimental');
  if (tag || doc.experimental !== undefined)
    out.push(experimentalLine(doc.experimental ?? tag?.text ?? ''));
  if (doc.deprecated !== undefined)
    out.push(`**Deprecated.**${doc.deprecated ? ` ${doc.deprecated}` : ''}`);
  if (doc.text) out.push(doc.text);
  if (e.decls.length > 0)
    out.push(`\`\`\`ts nocheck\n${e.decls.map(signature).join('\n')}\n\`\`\``);
  if (doc.params.length > 0) {
    out.push(
      [
        '| Parameter | Description |',
        '| --- | --- |',
        ...doc.params.map((p) => `| \`${p.name}\` | ${cell(p.text)} |`),
      ].join('\n'),
    );
  }
  if (doc.returns) out.push(`**Returns:** ${doc.returns}`);
  if (doc.throws.length > 0)
    out.push(['**Throws:**', ...doc.throws.map((t) => `- ${cell(t)}`)].join('\n'));
  const rows = e.kind === 'function' || e.kind === 'const' ? [] : memberRows(e.decls);
  if (rows.length > 0) {
    // Fields when it's all data, members when it has methods (or is a class).
    const head = e.kind === 'class' || rows.some((r) => r.includes('()`')) ? 'Member' : 'Field';
    out.push([`| ${head} | Description |`, '| --- | --- |', ...rows].join('\n'));
  }
  for (const x of doc.examples) out.push(`**Example:**\n\n${example(x)}`);
  const guides = ctx.guides(entry, e.name);
  if (guides.length > 0) out.push(`**Guides:** ${guides.join(', ')}.`);
  return out.join('\n\n');
}

/** One package's page. */
export function renderPage(
  title: string,
  lead: string,
  sections: readonly { entry: string; exports: readonly ApiExport[] }[],
  ctx: Context,
): string {
  const parts = [`# ${title}`, lead];
  for (const s of sections) {
    if (s.exports.length === 0) continue;
    parts.push(`## \`${s.entry}\``);
    for (const e of ordered(s.exports)) parts.push(renderExport(e, s.entry, ctx));
  }
  parts.push(GENERATED);
  return `${parts.join('\n\n')}\n`;
}

// --- The CLI page ------------------------------------------------------------

/** One flag as `--help` prints it: `-o, --out <file>` and its description. */
export type CliFlag = { flag: string; description: string };
export type CliCommand = {
  /** The command's words and what follows them: `contracts export <module>`. */
  usage: string;
  words: string;
  summary: string;
  details: string;
  flags: readonly CliFlag[];
};
export type Cli = { options: readonly CliFlag[]; commands: readonly CliCommand[] };

/** The `Options:` lines of a help text. */
function flagLines(help: string): CliFlag[] {
  const at = help.indexOf('\nOptions:\n');
  if (at < 0) return [];
  return help
    .slice(at + '\nOptions:\n'.length)
    .split('\n')
    .flatMap((l) => {
      const m = /^\s+(-\S.*?)\s{2,}(\S.*)$/.exec(l);
      return m ? [{ flag: (m[1] ?? '').trim(), description: (m[2] ?? '').trim() }] : [];
    });
}

/**
 * Reads the CLI from its own `--help` (decision 29): the top-level help lists
 * the commands, and each command's help gives its usage, summary, details and
 * flags. `helpOf` runs `isoloop <words> --help`.
 */
export function parseCli(top: string, helpOf: (words: string) => string): Cli {
  const list =
    top.slice(top.indexOf('\nCommands:\n') + '\nCommands:\n'.length).split('\n\n')[0] ?? '';
  const commands = list.split('\n').flatMap((l) => {
    const words = /^\s+(\S.*?)\s{2,}\S/.exec(l)?.[1];
    if (!words) return [];
    const help = helpOf(words);
    const usage = /^Usage: isoloop (.*?)(?: \[options\])?$/m.exec(help)?.[1] ?? words;
    const body = help.slice(help.indexOf('\n') + 1, help.indexOf('\nOptions:\n')).trim();
    const [summary = '', ...rest] = body.split(/\n\s*\n/);
    return [
      {
        words,
        usage,
        summary: summary.trim(),
        details: rest.join('\n\n').trim(),
        flags: flagLines(help),
      },
    ];
  });
  return { options: flagLines(top), commands };
}

/** Help text as Markdown: paragraphs at blank lines, `<` escaped so `<module>` shows. */
const helpText = (s: string): string =>
  s
    .split(/\n\s*\n/)
    .map((p) =>
      p
        .split('\n')
        .map((l) => l.trim())
        .join(' ')
        .replace(/</g, '\\<'),
    )
    .join('\n\n');

const sentence = (s: string): string => (/[.!?]$/.test(s) ? s : `${s}.`);

const flagTable = (flags: readonly CliFlag[]): string =>
  [
    '| Flag | Description |',
    '| --- | --- |',
    ...flags.map((f) => `| \`${f.flag}\` | ${cell(sentence(f.description))} |`),
  ].join('\n');

/** The page for the `isoloop` command line (decision 29). */
export function renderCli(cli: Cli): string {
  const parts = [
    '# The isoloop command line',
    'Every command of `isoloop`, with its usage and its flags, as its own `--help` gives them.',
  ];
  if (cli.options.length > 0) parts.push('## Options for every command', flagTable(cli.options));
  for (const c of cli.commands) {
    parts.push(`## \`isoloop ${c.words}\``, helpText(sentence(c.summary)));
    parts.push(`\`\`\`sh\nisoloop ${c.usage} [options]\n\`\`\``);
    if (c.details) parts.push(helpText(c.details));
    if (c.flags.length > 0) parts.push(flagTable(c.flags));
  }
  parts.push(GENERATED);
  return `${parts.join('\n\n')}\n`;
}

// --- The pages ---------------------------------------------------------------

/** The guide links for each export, from the map, with each guide's title. */
function guideLinks(map: DocsMap, title: (slug: string) => string): Context['guides'] {
  return (entry, name) =>
    Object.entries(map.guides)
      .filter(([, g]) => g.exports[entry]?.includes(name))
      .map(([slug]) => `[${title(slug)}](../guide/${slug}.md)`);
}

/** The package an entry point belongs to: `@isoloop/host/dev-mcp` → `host`. */
const packageOf = (entry: string): string => entry.split('/')[1] ?? entry;

/** The page an entry point is documented on. */
const pageOf = (entry: string): string => `${packageOf(entry)}.md`;

/** Every page, by file name, from a model of the published types. */
export function renderAll(
  api: ApiModel,
  map: DocsMap,
  guideTitle: (slug: string) => string,
  cli: Cli,
): Map<string, string> {
  const pages = new Map<string, string>();
  const guides = guideLinks(map, guideTitle);
  for (const pkg of USER_FACING) {
    const sections = [...api.entries]
      .filter(([entry]) => packageOf(entry) === pkg)
      .map(([entry, exports]) => ({ entry, exports }));
    if (sections.length === 0) continue;
    const lead = LEADS[pkg];
    const names = new Set(sections.flatMap((s) => s.exports.map((e) => e.name)));
    for (const [, code] of lead.matchAll(/`([A-Za-z_$][\w$]*)`/g)) {
      if (code && !names.has(code))
        throw new Error(`api: the ${pkg} lead names \`${code}\`, which it doesn't export`);
    }
    const page = `${pkg}.md`;
    pages.set(page, renderPage(`@isoloop/${pkg}`, lead, sections, { pageOf, page, guides }));
  }
  pages.set('cli.md', renderCli(cli));
  return pages;
}

/** Where a page still has a bundler suffix (`HostApi$1`): one `file:line: text` per hit. */
export function bundlerSuffixes(pages: ReadonlyMap<string, string>): string[] {
  return [...pages].flatMap(([file, md]) =>
    md.split('\n').flatMap((line, i) => {
      const hit = /[A-Za-z_]\w*\$\d+(?![\w$])/.exec(line);
      return hit ? [`${file}:${i + 1}: ${hit[0]}`] : [];
    }),
  );
}

/** The built CLI's help, read through `--help`. */
function cliFromHelp(root: string): Cli {
  const cli = join(root, 'packages/cli/dist/cli.js');
  const run = (args: string[]): string =>
    execFileSync(process.execPath, [cli, ...args], { encoding: 'utf8', cwd: root });
  return parseCli(run(['--help']), (words) => run([...words.split(' '), '--help']));
}

/** A guide's title, its h1. */
const titleOf =
  (root: string) =>
  (slug: string): string => {
    const md = readFileSync(join(root, 'docs/guide', `${slug}.md`), 'utf8');
    return /^# (.+)$/m.exec(md)?.[1]?.trim() ?? slug;
  };

async function main(): Promise<void> {
  const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
  const check = process.argv.includes('--check');
  const files = entryFiles(root);
  const missing = files.find((f) => !existsSync(f.file));
  if (missing) {
    console.error(
      `docs:api: no built types at ${relative(root, missing.file)}: run pnpm build first`,
    );
    process.exitCode = 1;
    return;
  }
  const map = parseMap(readFileSync(join(root, 'docs/guide/map.json'), 'utf8'));
  const pages = renderAll(readApi(files, root), map, titleOf(root), cliFromHelp(root));
  const leaked = bundlerSuffixes(pages);
  if (leaked.length > 0) {
    console.error(`docs:api: bundler name suffixes leaked into the pages:\n${leaked.join('\n')}`);
    process.exitCode = 1;
    return;
  }
  const dir = join(root, API_DIR);
  if (check) {
    const onDisk = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.md')) : [];
    const stale = [
      ...[...pages]
        .filter(([f, md]) => !existsSync(join(dir, f)) || readFileSync(join(dir, f), 'utf8') !== md)
        .map(([f]) => f),
      ...onDisk.filter((f) => !pages.has(f)),
    ];
    if (stale.length > 0) {
      const say = process.env.CI
        ? (m: string) => console.log(`::error file=${API_DIR}::${m}`)
        : console.error;
      say(
        `${API_DIR} is out of date (${stale.join(', ')}): run pnpm build, then pnpm docs:api, and commit the result`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`docs:api: ${pages.size} pages up to date`);
    return;
  }
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir))
    if (f.endsWith('.md') && !pages.has(f)) unlinkSync(join(dir, f));
  for (const [f, md] of pages) writeFileSync(join(dir, f), md);
  console.log(`docs:api: wrote ${pages.size} pages to ${API_DIR}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();

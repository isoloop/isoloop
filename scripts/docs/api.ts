// The API reference (M4c, decisions 27–29): one page per user-facing package
// in docs/api, generated from the published `.d.ts` through readApi, and the
// CLI's page from its commands. The pages are never edited by hand: CI fails
// when they differ from a fresh run (`pnpm docs:api --check`), and
// `pnpm docs:api` writes them again.
//
// A page: the package as the title, a one-sentence lead, then a section (h2)
// per entry point, and in it one h3 per export. Exports are grouped, functions
// first, then classes, constants and types, each group alphabetical, so the
// calls a reader starts from lead each section. Each export has its
// Experimental line when tagged, its doc comment, its declaration in a
// `ts nocheck` fence, its parameters, returns, throws and fields, its
// examples, and links to the guides that list it in docs/guide/map.json.

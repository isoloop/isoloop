// What's particular to a repo, read from `rules.config.json` at its root
// (ADR 0026, amended 2026-11-28). The scripts hold nothing about one project:
// every name, path and link below comes from that file or a neutral default.
import { existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export const CONFIG_FILE = 'rules.config.json';

export interface RulesConfig {
  /** The page's and the README's title. */
  title: string;
  /** The README's first paragraph, in Markdown. */
  readmeIntro: string;
  /** Where the concept files, `concepts.json` and `keywords.json` live. */
  rulesDir: string;
  /** Where the ADRs live, as `NNNN-title.md`. */
  adrDir: string;
  /** From this ADR number on, every decision and amendment has a `Rules:` line from the start. */
  rulesLinesFrom: string;
  /** Owner and repo on GitHub, for links from refs. */
  github: { owner: string; repo: string };
  /** Where the published packages live, to read the shared version; empty when there are none. */
  packagesDir: string;
  /** Where `rules:board` writes the page (gitignore it). */
  boardOut: string;
  /** Derived links between rules. */
  links: { cap: number };
  /** Backticked names that aren't symbols worth linking or searching by. */
  symbolsIgnore: string[];
}

export const DEFAULTS: RulesConfig = {
  title: 'Rules',
  readmeIntro:
    'What holds today, one fact per rule, with every decision that touched it. Generated by `pnpm rules:build` from the JSON files in this folder; edit those, not this file.',
  rulesDir: 'docs/rules',
  adrDir: 'docs/adr',
  rulesLinesFrom: '9999',
  github: { owner: '', repo: '' },
  packagesDir: '',
  boardOut: '.rules-board/index.html',
  links: { cap: 12 },
  symbolsIgnore: [],
};

const isRec = (v: unknown): v is Record<string, unknown> =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

/** The config at `root`, merged over the defaults; throws on a field of the wrong type. */
export function loadConfig(root: string): RulesConfig {
  const path = join(root, CONFIG_FILE);
  if (!existsSync(path)) return DEFAULTS;
  const raw: unknown = JSON.parse(readFileSync(path, 'utf8'));
  return parseConfig(raw);
}

/** Validates and merges one parsed config over the defaults. */
export function parseConfig(raw: unknown): RulesConfig {
  if (!isRec(raw)) throw new Error(`${CONFIG_FILE}: must be an object`);
  const out: RulesConfig = {
    ...DEFAULTS,
    github: { ...DEFAULTS.github },
    links: { ...DEFAULTS.links },
  };
  for (const [k, v] of Object.entries(raw)) {
    if (k === '$schema') continue;
    if (!(k in DEFAULTS)) throw new Error(`${CONFIG_FILE}: unknown field "${k}"`);
    const want: unknown = Reflect.get(DEFAULTS, k);
    if (typeof want === 'string') {
      if (typeof v !== 'string') throw new Error(`${CONFIG_FILE}: "${k}" must be a string`);
      Reflect.set(out, k, v);
    } else if (Array.isArray(want)) {
      if (!Array.isArray(v) || !v.every((x) => typeof x === 'string'))
        throw new Error(`${CONFIG_FILE}: "${k}" must be an array of strings`);
      Reflect.set(out, k, v);
    } else {
      if (!isRec(v) || !isRec(want)) throw new Error(`${CONFIG_FILE}: "${k}" must be an object`);
      const merged: Record<string, unknown> = { ...want };
      for (const [kk, vv] of Object.entries(v)) {
        const w: unknown = want[kk];
        if (w === undefined) throw new Error(`${CONFIG_FILE}: unknown field "${k}.${kk}"`);
        if (typeof vv !== typeof w)
          throw new Error(`${CONFIG_FILE}: "${k}.${kk}" must be a ${typeof w}`);
        merged[kk] = vv;
      }
      Reflect.set(out, k, merged);
    }
  }
  return out;
}

/** The repo these scripts run in, and its config. */
export const REPO_ROOT = resolve(import.meta.dirname, '../..');
export const CONFIG: RulesConfig = loadConfig(REPO_ROOT);
